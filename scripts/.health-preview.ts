import { createPool, migrate } from '../server/db';
import { createUser } from '../server/auth';
import { createApp } from '../server/app';
import { createRequester } from '../server/network';
import { loadConfig } from '../server/config';
const base = createPool('postgresql://pipeline_test@127.0.0.1:55439/postgres');
const schema = 'health_preview_' + Date.now();
await base.query(`CREATE SCHEMA ${schema}`);
const url = new URL('postgresql://pipeline_test@127.0.0.1:55439/postgres');
url.searchParams.set('options', `-c search_path=${schema}`);
const config = loadConfig({ NODE_ENV: 'test', DATABASE_URL: url.href, APP_ORIGIN: 'http://127.0.0.1:18081', ENCRYPTION_KEY: Buffer.alloc(32, 7).toString('base64'), WORKER_ENABLED: 'false' });
const pool = createPool(url.href);
await migrate(pool);
await createUser(pool, 'health-preview', 'Preview-Health-Only-2026!', 'ADMIN');
const server = createApp(pool, config, createRequester(config)).listen(18081, '127.0.0.1', () => console.log('Isolated health preview ready on port 18081'));
process.on('SIGTERM', async () => {
  server.close();
  await pool.end();
  await base.query(`DROP SCHEMA ${schema} CASCADE`);
  await base.end();
  process.exit(0);
});
